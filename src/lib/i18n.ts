// Flatten nested translation keys for dot-notation access
function getNestedValue(obj: NestedTranslations | string, key: string): string | undefined {
  const keys = key.split('.');
  let current: NestedTranslations | string = obj;
  for (let i = 0; i < keys.length; i++) {
    if (typeof current === 'string') return undefined;
    const k = keys[i];
    if (current[k] !== undefined) {
      current = current[k];
    } else {
      // Try joining remaining keys as a flat dot-key (e.g. 'status.IN_YARD')
      const remainingKey = keys.slice(i).join('.');
      if (current[remainingKey] !== undefined) {
        current = current[remainingKey];
        break;
      }
      return undefined;
    }
  }
  return typeof current === 'string' ? current : undefined;
}

export function t(
  lang: Language,
  key: string,
  params?: Record<string, string | number>
): string {
  const langTranslations = translations[lang] || translations.en;
  let value = getNestedValue(langTranslations, key);

  // Fallback to English
  if (value === undefined) {
    value = getNestedValue(translations.en, key);
  }

  // Return key if not found
  if (value === undefined) return key;

  // Replace parameters like {name}, {count}, etc.
  if (params) {
    for (const [paramKey, paramValue] of Object.entries(params)) {
      value = value.replace(`{${paramKey}}`, String(paramValue));
    }
  }

  return value;
}

